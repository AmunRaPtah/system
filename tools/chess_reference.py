#!/usr/bin/env python3
"""Generate ios/EngineTests/ChessReference.swift from python-chess.

The Swift engine self-test (ios/EngineTests/main.swift, run in CI with swiftc)
compares its perft counts and SAN output against these reference values.

    pip install chess && python3 tools/chess_reference.py
"""
import pathlib
import chess

# (name, fen, perft depth)
POSITIONS = [
    ("start", chess.STARTING_FEN, 4),
    ("kiwipete", "r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1", 3),
    ("pos3", "8/2p5/3p4/KP5r/1R3p1k/8/4P1P1/8 w - - 0 1", 4),
    ("pos4", "r3k2r/Pppp1ppp/1b3nbN/nP6/BBP1P3/q4N2/Pp1P2PP/R2Q1RK1 w kq - 0 1", 3),
    ("pos5", "rnbq1k1r/pp1Pbppp/2p5/8/2B5/8/PPP1NnPP/RNBQK2R w KQ - 1 8", 3),
    ("pos6", "r4rk1/1pp1qppp/p1np1n2/2b1p1B1/2B1P1b1/P1NP1N2/1PP1QPPP/R4RK1 w - - 0 10", 3),
    ("knights", "7k/8/8/3N1N2/8/3N4/8/K7 w - - 0 1", 2),
    ("mate", "6k1/5ppp/8/8/8/8/8/R5K1 w - - 0 1", 3),
]


def perft(b, d):
    if d == 0:
        return 1
    n = 0
    for m in b.legal_moves:
        b.push(m)
        n += perft(b, d - 1)
        b.pop()
    return n


def fnv(s):
    h = 0xcbf29ce484222325
    for c in s.encode():
        h ^= c
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def san_lines(b):
    """Every 'uci san' pair at depth 1 and depth 2, sorted, newline-joined."""
    out = []
    for m in b.legal_moves:
        out.append(f"{m.uci()} {b.san(m)}")
        b.push(m)
        for m2 in b.legal_moves:
            out.append(f"{m.uci()} {m2.uci()} {b.san(m2)}")
        b.pop()
    return "\n".join(sorted(out))


rows = []
for name, fen, depth in POSITIONS:
    b = chess.Board(fen)
    n = perft(b, depth)
    s = san_lines(b)
    rows.append(f'    ChessRef(name: "{name}", fen: "{fen}", depth: {depth}, nodes: {n}, '
                f'sanCount: {s.count(chr(10)) + 1}, sanHash: 0x{fnv(s):016x}),')
    print(f"{name:10s} depth {depth}: {n}")

out = pathlib.Path(__file__).resolve().parents[1] / "ios/EngineTests/ChessReference.swift"
out.write_text(
    "// Generated by tools/chess_reference.py (python-chess " + chess.__version__ + "). Do not edit.\n\n"
    "struct ChessRef { let name: String; let fen: String; let depth: Int; let nodes: Int; let sanCount: Int; let sanHash: UInt64 }\n\n"
    "let chessReference: [ChessRef] = [\n" + "\n".join(rows) + "\n]\n"
)
print("wrote", out)
